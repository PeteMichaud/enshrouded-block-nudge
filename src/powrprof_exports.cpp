// BlockNudge as POWRPROF.dll. Enshrouded loads POWRPROF.dll from its own folder at start-up
// and no other mod claims that name, unlike dinput8.dll. Every export of the real powrprof.dll
// is forwarded to it, so the game and Windows code in the process get the real functions;
// BlockNudge itself starts from DllMain (proxy.cpp) as under any name.
//
// Forwarders name the real DLL by absolute path (\\.\GLOBALROOT\SystemRoot\System32), so they
// never resolve back to this file. A .def file cannot express that (it splits at the first dot);
// a linker /export directive can. MSVC only.
//
// Generated from C:\Windows\System32\powrprof.dll (139 exports): dumpbin /exports

#ifndef _MSC_VER
#error "POWRPROF.dll forwarders need the MSVC linker; build the dinput8 target with MinGW"
#endif

